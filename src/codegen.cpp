// Formats a double so the emitted literal round-trips exactly. std::to_string
// gives six decimals, which would silently change the design: a gain of
// 2.6383607501 written as 2.638361 is a different controller.
std::string Literal(double value) {
    if (!std::isfinite(value)) {
        throw std::invalid_argument(
            "codegen: a value to emit is not finite, so there is nothing to "
            "emit");
    }
    std::ostringstream text;
    text << std::setprecision(17) << value;
    std::string rendered = text.str();
    if (rendered.find('.') == std::string::npos &&
        rendered.find('e') == std::string::npos &&
        rendered.find("inf") == std::string::npos &&
        rendered.find("nan") == std::string::npos) {
        rendered += ".0";
    }
    return rendered;
}

// Wraps a value so that emitting it into a float array is not a narrowing
// conversion. `float k[1]{0.30000000000000004}` is ill-formed - the value is
// not exactly representable - and it is only a matter of which gain a design
// happens to produce before a build breaks in the field. The explicit cast
// makes the conversion intentional, which is what it is.
std::string CastLiteral(double value) {
    return "static_cast<Real>(" + Literal(value) + ")";
}

std::string ArrayLiteral(const Matrix& matrix, const std::string& indent) {
    std::ostringstream text;
    for (Eigen::Index row = 0; row < matrix.rows(); ++row) {
        text << indent << "{";
        for (Eigen::Index column = 0; column < matrix.cols(); ++column) {
            if (column > 0) {
                text << ", ";
            }
            text << CastLiteral(matrix(row, column));
        }
        text << "}";
        if (row + 1 < matrix.rows()) {
            text << ",";
        }
        text << "\n";
    }
    return text.str();
}

std::string UnitSuffix(const std::string& unit) {
    return unit.empty() ? std::string() : " [" + unit + "]";
}

// Formats the whole unit list for a comment: "m, m/s" reads better in a
// generated header than repeating the first entry for every channel.
std::string UnitList(const std::vector<std::string>& units) {
    if (units.empty()) {
        return std::string();
    }
    std::string rendered = " [";
    for (std::size_t i = 0; i < units.size(); ++i) {
        if (i > 0) {
            rendered += ", ";
        }
        rendered += units[i];
    }
    rendered += "]";
    return rendered;
}

// The one place a controller is emitted. Every combination (full state or
// observer) x (with or without integral action) goes through here, because the
// alternative - one code path per combination - is how the integral version
// ended up announcing integral action while emitting none.
struct EmitSpec {
    const LtiSystem* system = nullptr;
    Matrix state_gain;     // m x n
    Matrix integral_gain;  // m x 1, empty when there is no integral action
    const Matrix* observer_gain = nullptr;
    CodegenOptions options;
    std::string design_note;
    std::string observer_note;
};

CodegenResult Emit(const EmitSpec& spec) {
    const LtiSystem& system = *spec.system;
    const int n = system.state_dimension();
    const int m = system.input_dimension();
    const int p = system.output_dimension();
    const bool has_observer = spec.observer_gain != nullptr;
    const bool has_integral = spec.integral_gain.size() > 0;
    const CodegenOptions& options = spec.options;

    CodegenResult result;
    result.state_dimension = n;
    result.input_dimension = m;
    result.output_dimension = p;
    result.has_observer = has_observer;
    result.has_integral_action = has_integral;
    result.state_feedback_gain = spec.state_gain;
    if (has_integral) {
        result.integral_gain = spec.integral_gain;
    }
    if (has_observer) {
        result.observer_gain = *spec.observer_gain;
    }
    result.suggested_filename = options.controller_name + ".h";

    const std::string guard =
        options.namespace_name + "_" + options.controller_name + "_H_";
    std::ostringstream code;
    code << "// Generated by the control-design library. Do not edit by hand:\n"
         << "// regenerate from the design instead, so the code and the design "
            "cannot\n"
         << "// drift apart.\n"
         << "//\n"
         << "// "
         << (options.provenance.empty() ? "design provenance not recorded"
                                        : options.provenance)
         << "\n"
         << "//\n"
         << "// Sample time: " << Literal(system.sample_time()) << " s\n"
         << "// States: " << n << ", inputs: " << m << ", outputs: " << p
         << "\n"
         << "// State feedback: u = -K x"
         << (has_integral ? " - Ki z, with z the integral of the tracking error"
                          : "")
         << "\n"
         << "// State source: "
         << (has_observer ? "measured outputs through a state observer"
                          : "measured state (full state feedback)")
         << "\n"
         << "\n"
         << "#ifndef " << guard << "\n"
         << "#define " << guard << "\n"
         << "\n"
         << "#include <array>\n"
         << "#include <cmath>\n"
         << "#include <cstddef>\n"
         << "\n"
         << "namespace " << options.namespace_name << " {\n"
         << "\n"
         << "// Single place to switch the target between float and double.\n"
         << "using Real = " << options.real_type << ";\n"
         << "\n"
         << "// Saturating limit. No division, no data-dependent loop: the "
            "per-tick\n"
         << "// cost is the same on every call, which is what makes a deadline "
            "testable.\n"
         << "inline Real Limit(Real value, Real lower, Real upper) {\n"
         << "    return value < lower ? lower : (value > upper ? upper : "
            "value);\n"
         << "}\n"
         << "\n"
         << "class " << options.controller_name << " {\n"
         << "public:\n"
         << "    static constexpr std::size_t kStates = " << n << ";\n"
         << "    static constexpr std::size_t kInputs = " << m << ";\n"
         << "    static constexpr std::size_t kOutputs = " << p << ";\n"
         << "    // Sample period [s]: the rate Update() must be called at.\n"
         << "    static constexpr Real kSampleTime = "
         << CastLiteral(system.sample_time()) << ";\n"
         << "\n"
         << "    " << options.controller_name << "() { Reset(); }\n"
         << "\n"
         << "    // Clears the estimated state, the integrator and the "
            "previous output.\n"
         << "    void Reset() {\n"
         << "        x_hat_.fill(static_cast<Real>(0));\n"
         << "        integral_.fill(static_cast<Real>(0));\n"
         << "        u_prev_.fill(static_cast<Real>(0));\n"
         << "        error_ = 0;\n"
         << "        saturated_ = false;\n"
         << "    }\n"
         << "\n"
         << "    // One control period.\n"
         << "    //   measurement: "
         << (has_observer ? "measured outputs, kOutputs entries"
                          : "measured states, kStates entries")
         << (has_observer ? UnitSuffix(options.output_unit)
                          : UnitList(options.state_units))
         << "\n"
         << "    //   setpoint:    reference for output 0"
         << UnitSuffix(options.output_unit) << "\n"
         << "    //   returns:     actuator command, kInputs entries, written "
            "to\n"
         << "    //                `command`" << UnitSuffix(options.input_unit)
         << "\n"
         << "    // A non-finite measurement sets error() and repeats the "
            "previous\n"
         << "    // command: driving an actuator from a NaN is worse than "
            "holding still.\n"
         << "    void Update(const Real* measurement, Real setpoint, Real* "
            "command) {\n"
         << "        if (measurement == nullptr || command == nullptr) {\n"
         << "            error_ = 2;\n"
         << "            return;\n"
         << "        }\n"
         << "        for (std::size_t i = 0; i < "
         << (has_observer ? "kOutputs" : "kStates") << "; ++i) {\n"
         << "            if "
            "(!std::isfinite(static_cast<double>(measurement[i]))) {\n"
         << "                error_ = 1;\n"
         << "                for (std::size_t j = 0; j < kInputs; ++j) {\n"
         << "                    command[j] = u_prev_[j];\n"
         << "                }\n"
         << "                return;\n"
         << "            }\n"
         << "        }\n"
         << "        error_ = 0;\n";

    if (has_observer) {
        code << "\n"
             << "        // Observer prediction: x_hat- = Ad x_hat + Bd "
                "u_prev.\n"
             << "        Real predicted[kStates] = {};\n"
             << "        for (std::size_t i = 0; i < kStates; ++i) {\n"
             << "            Real sum = static_cast<Real>(0);\n"
             << "            for (std::size_t j = 0; j < kStates; ++j) {\n"
             << "                sum += kAd[i][j] * x_hat_[j];\n"
             << "            }\n"
             << "            for (std::size_t j = 0; j < kInputs; ++j) {\n"
             << "                sum += kBd[i][j] * u_prev_[j];\n"
             << "            }\n"
             << "            predicted[i] = sum;\n"
             << "        }\n"
             << "        // Innovation: y_hat = Cd x_hat-, then e_y = y - "
                "y_hat.\n"
             << "        Real innovation[kOutputs] = {};\n"
             << "        for (std::size_t i = 0; i < kOutputs; ++i) {\n"
             << "            Real sum = static_cast<Real>(0);\n"
             << "            for (std::size_t j = 0; j < kStates; ++j) {\n"
             << "                sum += kCd[i][j] * predicted[j];\n"
             << "            }\n"
             << "            innovation[i] = measurement[i] - sum;\n"
             << "        }\n"
             << "        // Correction: x_hat = x_hat- + L e_y.\n"
             << "        for (std::size_t i = 0; i < kStates; ++i) {\n"
             << "            Real sum = static_cast<Real>(0);\n"
             << "            for (std::size_t j = 0; j < kOutputs; ++j) {\n"
             << "                sum += kL[i][j] * innovation[j];\n"
             << "            }\n"
             << "            x_hat_[i] = predicted[i] + sum;\n"
             << "        }\n";
    } else {
        code << "\n"
             << "        // Full state feedback: the measurement is the state "
                "estimate.\n"
             << "        for (std::size_t i = 0; i < kStates; ++i) {\n"
             << "            x_hat_[i] = measurement[i];\n"
             << "        }\n";
    }

    if (has_integral) {
        code << "\n"
             << "        // Tracked output y = Cd[0] x_hat"
             << UnitSuffix(options.output_unit) << ".\n"
             << "        Real output = static_cast<Real>(0);\n"
             << "        for (std::size_t j = 0; j < kStates; ++j) {\n"
             << "                output += kCd[0][j] * x_hat_[j];\n"
             << "        }\n"
             << "        const Real tracking_error = setpoint - output;\n";
    } else {
        // The reference is unused without an integrator, and an emitted unused
        // local would be a warning in the firmware build that compiles this
        // file.
        code << "\n"
             << "        static_cast<void>(setpoint);  // no integral action\n";
    }

    if (has_integral) {
        code << "\n"
             << "        // Integrator, held when the command is clipped in "
                "the same\n"
             << "        // direction as the error. Without the hold, the "
                "integrator winds\n"
             << "        // up while the actuator cannot respond and the loop "
                "overshoots on\n"
             << "        // the way back.\n"
             << "        const bool winding_up =\n"
             << "            (saturated_ && ((u_prev_[0] > "
             << CastLiteral(options.saturate ? options.input_max : 0.0)
             << " && tracking_error > static_cast<Real>(0)) ||\n"
             << "                            (u_prev_[0] < "
             << CastLiteral(options.saturate ? options.input_min : 0.0)
             << " && tracking_error < static_cast<Real>(0))));\n"
             << "        if (!winding_up) {\n"
             << "            integral_[0] += kSampleTime * tracking_error;\n"
             << "        }\n";
    }

    code << "\n"
         << "        // State feedback: u = -K x_hat";
    if (has_integral) {
        code << " - Ki z";
    }
    code << ".\n"
         << "        for (std::size_t i = 0; i < kInputs; ++i) {\n"
         << "            Real sum = static_cast<Real>(0);\n"
         << "            for (std::size_t j = 0; j < kStates; ++j) {\n"
         << "                sum -= kK[i][j] * x_hat_[j];\n"
         << "            }\n";
    if (has_integral) {
        code << "            sum -= kKi[i] * integral_[0];\n";
    }
    code << "            command[i] = sum;\n"
         << "        }\n";

    if (options.saturate) {
        code << "\n"
             << "        // Actuator limit.\n"
             << "        saturated_ = false;\n"
             << "        for (std::size_t i = 0; i < kInputs; ++i) {\n"
             << "            const Real unclipped = command[i];\n"
             << "            command[i] = Limit(command[i], "
             << CastLiteral(options.input_min) << ", "
             << CastLiteral(options.input_max) << ");\n"
             << "            if (command[i] != unclipped) {\n"
             << "                saturated_ = true;\n"
             << "            }\n"
             << "        }\n";
    } else {
        code << "\n"
             << "        saturated_ = false;\n";
    }

    code << "\n"
         << "        for (std::size_t i = 0; i < kInputs; ++i) {\n"
         << "            u_prev_[i] = command[i];\n"
         << "        }\n"
         << "    }\n"
         << "\n"
         << "    // Estimated state, in the device's own coordinates.\n"
         << "    const std::array<Real, kStates>& state_estimate() const { "
            "return x_hat_; }\n"
         << "    // Integrator state"
         << UnitSuffix(options.output_unit.empty() ? std::string()
                                                   : options.output_unit + "*s")
         << ".\n"
         << "    Real integral_state() const { return integral_[0]; }\n"
         << "    // Previous actuator command.\n"
         << "    Real last_input(std::size_t channel) const { return "
            "u_prev_[channel]; }\n"
         << "    // True when the last command was clipped by the actuator "
            "limit.\n"
         << "    bool saturated() const { return saturated_; }\n"
         << "    // 0 = normal, 1 = non-finite measurement, 2 = null pointer.\n"
         << "    int error() const { return error_; }\n"
         << "\n"
         << "private:\n"
         << "    // --- design constants "
            "-------------------------------------------------\n"
         << "    // State feedback gain K, from "
         << (spec.design_note.empty() ? "the design" : spec.design_note) << "\n"
         << "    static constexpr Real kK[kInputs][kStates] = {\n"
         << ArrayLiteral(spec.state_gain, "        ") << "    };\n";
    if (has_integral) {
        code << "    // Integral gain Ki, on z = integral of the tracking "
                "error.\n"
             << "    static constexpr Real kKi[kInputs] = {\n"
             << "        ";
        for (Eigen::Index i = 0; i < spec.integral_gain.rows(); ++i) {
            if (i > 0) {
                code << ", ";
            }
            code << CastLiteral(spec.integral_gain(i, 0));
        }
        code << "};\n";
    }
    code << "    // Plant matrices, discretized with zero-order hold at "
            "kSampleTime.\n"
         << "    static constexpr Real kAd[kStates][kStates] = {\n"
         << ArrayLiteral(system.a(), "        ") << "    };\n"
         << "    static constexpr Real kBd[kStates][kInputs] = {\n"
         << ArrayLiteral(system.b(), "        ") << "    };\n"
         << "    static constexpr Real kCd[kOutputs][kStates] = {\n"
         << ArrayLiteral(system.c(), "        ") << "    };\n";
    if (has_observer) {
        code << "    // Observer gain L, from "
             << (spec.observer_note.empty() ? "the design" : spec.observer_note)
             << "\n"
             << "    static constexpr Real kL[kStates][kOutputs] = {\n"
             << ArrayLiteral(*spec.observer_gain, "        ") << "    };\n";
    }
    code << "\n"
         << "    // --- run-time state "
            "---------------------------------------------------\n"
         << "    std::array<Real, kStates> x_hat_{};\n"
         << "    std::array<Real, 1> integral_{};\n"
         << "    std::array<Real, kInputs> u_prev_{};\n"
         << "    int error_ = 0;\n"
         << "    bool saturated_ = false;\n"
         << "};\n"
         << "\n"
         << "}  // namespace " << options.namespace_name << "\n"
         << "\n"
         << "#endif  // " << guard << "\n";

    std::ostringstream usage;
    usage << "// Usage (call at exactly kSampleTime):\n"
          << "//   " << options.namespace_name
          << "::" << options.controller_name << " controller;\n"
          << "//   controller.Reset();\n"
          << "//   " << options.real_type << " measurement["
          << (has_observer ? p : n) << "] = { ... };  // "
          << (has_observer ? "sensor outputs" : "measured states") << "\n"
          << "//   " << options.real_type << " command[" << m << "] = {};\n"
          << "//   controller.Update(measurement, setpoint, command);\n"
          << "//   if (controller.error() != 0) { /* sensor fault: hold or "
             "shut down */ }\n"
          << "//   if (controller.saturated()) { /* actuator limit reached */ "
             "}\n";
    result.usage_example = usage.str();
    code << "\n" << usage.str();
    result.header = code.str();
    return result;
}

