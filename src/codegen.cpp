std::string FormatDesignSummary(const DesignResult& result,
                                const std::string& label) {
    std::ostringstream text;
    text << label << "\n";
    text << "  gain:\n";
    for (Eigen::Index row = 0; row < result.gain.rows(); ++row) {
        text << "    [";
        for (Eigen::Index column = 0; column < result.gain.cols(); ++column) {
            text << std::setw(12) << std::setprecision(6) << std::fixed
                 << result.gain(row, column);
        }
        text << " ]\n";
    }
    text << "  closed-loop poles:";
    for (Eigen::Index i = 0; i < result.closed_loop_poles.size(); ++i) {
        text << " " << std::setprecision(4)
             << result.closed_loop_poles(i).real();
        if (std::abs(result.closed_loop_poles(i).imag()) > 1e-12) {
            text << (result.closed_loop_poles(i).imag() >= 0 ? "+" : "-")
                 << std::abs(result.closed_loop_poles(i).imag()) << "j";
        }
    }
    text << "\n  damping:";
    for (Eigen::Index i = 0; i < result.damping_ratios.size(); ++i) {
        text << " " << std::setprecision(3) << result.damping_ratios(i);
    }
    text << "\n  largest gain: " << std::setprecision(4)
         << result.gain_magnitude << "\n";
    if (!result.notes.empty()) {
        text << "  note: " << result.notes << "\n";
    }
    for (const std::string& warning : result.warnings) {
        text << "  WARNING: " << warning << "\n";
    }
    return text.str();
}

CodegenResult GenerateController(const LtiSystem& system,
                                 const DesignResult& design,
                                 const CodegenOptions& options,
                                 const DesignResult* observer) {
    system.Validate("GenerateController");
    if (!system.is_discrete()) {
        throw std::invalid_argument(
            "GenerateController: the model must be discrete. The emitted "
            "controller "
            "steps its observer with the model's own matrices, so it has to be "
            "the "
            "sampled model the firmware will run against");
    }
    const int n = system.state_dimension();
    const int m = system.input_dimension();
    const int p = system.output_dimension();
    if (design.gain.rows() != m || design.gain.cols() != n) {
        throw std::invalid_argument(
            "GenerateController: the gain must be m x n of the model (" +
            std::to_string(m) + "x" + std::to_string(n) + " expected, " +
            std::to_string(design.gain.rows()) + "x" +
            std::to_string(design.gain.cols()) +
            " given). A gain with one extra column means the design included "
            "integral action; emit it with GenerateControllerWithIntegral so "
            "the "
            "integrator is actually implemented");
    }
    if (observer != nullptr &&
        (observer->gain.rows() != n || observer->gain.cols() != p)) {
        throw std::invalid_argument(
            "GenerateController: the observer gain must be n x p");
    }

    EmitSpec spec;
    spec.system = &system;
    spec.state_gain = design.gain;
    spec.observer_gain = observer != nullptr ? &observer->gain : nullptr;
    spec.options = options;
    spec.design_note = design.notes;
    spec.observer_note = observer != nullptr ? observer->notes : std::string();
    return Emit(spec);
}

CodegenResult GenerateControllerWithIntegral(
    const LtiSystem& system, const AugmentedDesign& augmented_design,
    const CodegenOptions& options, const DesignResult* observer) {
    system.Validate("GenerateControllerWithIntegral");
    if (!system.is_discrete()) {
        throw std::invalid_argument(
            "GenerateControllerWithIntegral: the model must be discrete");
    }
    const int n = system.state_dimension();
    const int m = system.input_dimension();
    const int p = system.output_dimension();
    // The augmented design carries a gain on [x; z]; the emitted controller has
    // to integrate the same error with the same convention, or the code is not
    // the design. Requiring the augmented system to be discrete at the plant's
    // sample time is what makes that checkable.
    if (!augmented_design.augmented.is_discrete() ||
        std::abs(augmented_design.augmented.sample_time() -
                 system.sample_time()) > 0.0) {
        throw std::invalid_argument(
            "GenerateControllerWithIntegral: the augmented model must be "
            "discrete at "
            "the same sample time as the plant model");
    }
    if (augmented_design.augmented.state_dimension() != n + 1) {
        throw std::invalid_argument(
            "GenerateControllerWithIntegral: the augmented model must have "
            "exactly one "
            "extra state (the integrator)");
    }
    const Matrix& gain = augmented_design.design.gain;
    if (gain.rows() != m || gain.cols() != n + 1) {
        throw std::invalid_argument(
            "GenerateControllerWithIntegral: the gain must be m x (n+1)");
    }
    if (observer != nullptr &&
        (observer->gain.rows() != n || observer->gain.cols() != p)) {
        throw std::invalid_argument(
            "GenerateControllerWithIntegral: the observer gain must be n x p");
    }

    EmitSpec spec;
    spec.system = &system;
    spec.state_gain = gain.leftCols(n);
    spec.integral_gain = gain.rightCols(1);
    spec.observer_gain = observer != nullptr ? &observer->gain : nullptr;
    spec.options = options;
    spec.design_note = augmented_design.design.notes;
    spec.observer_note = observer != nullptr ? observer->notes : std::string();
    return Emit(spec);
}

